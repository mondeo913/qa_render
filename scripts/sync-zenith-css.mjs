import { readFileSync, writeFileSync } from 'node:fs';
const css = ['resources/css/_shadcn-zenith.scss', 'resources/css/_zenith-controls.scss', 'resources/css/_reports.scss', 'resources/css/_dashboard.scss'].map(path => readFileSync(path, 'utf8')).join('\n');
const target = 'public/siget-zenith-runtime.css';
const result = '/* Generated by scripts/sync-zenith-css.mjs. Do not edit manually. */\n' + css;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== result) throw new Error('Zenith fallback is out of sync. Run npm run sync:ui.');
} else writeFileSync(target, result);
